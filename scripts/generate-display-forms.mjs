function codepointToChar(value) {
  return String.fromCodePoint(Number.parseInt(value.replace(/^U\+/, ""), 16));
}

function parseVariantCodes(value) {
  return value
    .split(/\s+/)
    .map((token) => token.replace(/<.*$/, ""))
    .filter((token) => /^U\+[0-9A-F]+$/i.test(token))
    .map(codepointToChar);
}

function loadRows() {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext(`${fs.readFileSync(dataPath, "utf8")}\nthis.rows = COMPACT_DICTIONARY;`, ctx);
  return ctx.rows;
}

const simplified = {};
for (const line of fs.readFileSync(variantsPath, "utf8").split(/\r?\n/)) {
  if (!line || line.startsWith("#")) continue;
  const match = line.match(/^(U\+[0-9A-F]+)\s+kSimplifiedVariant\s+(.+)$/);
  if (!match) continue;
  const [source, targets] = [codepointToChar(match[1]), parseVariantCodes(match[2])];
  if (targets.length) simplified[source] = targets[0];
}

const rows = loadRows();
const rowChars = new Set(rows.map((row) => row[0]));
const japanese = {};
for (const [oldForm, newForm] of Object.entries(manualJapaneseForms)) {
  if (rowChars.has(oldForm) || rowChars.has(newForm)) japanese[oldForm] = newForm;
}

const body = [
  "// Generated by scripts/generate-display-forms.mjs.",
  "const HAN_DISPLAY_FORMS = " + JSON.stringify({ simplified, japanese }) + ";",
  "",
].join("\n");

fs.writeFileSync(outputPath, body, "utf8");
console.log(`Done. simplified=${Object.keys(simplified).length}, japanese=${Object.keys(japanese).length}`);
