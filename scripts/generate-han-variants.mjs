import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const variantsPath = path.join(repoRoot, "data", "cache", "unihan", "Unihan_Variants.txt");
const irgPath = path.join(repoRoot, "data", "cache", "unihan", "Unihan_IRGSources.txt");
const outputPath = path.join(repoRoot, "han-variants.js");

const safeVariantFields = new Set([
  "kCompatibilityVariant",
  "kSimplifiedVariant",
  "kTraditionalVariant",
  "kZVariant",
]);

const manualPairs = [
  ["靑", "青"],
];

const graph = new Map();

function codepointToChar(value) {
  return String.fromCodePoint(Number.parseInt(value.replace(/^U\+/, ""), 16));
}

function addPair(left, right) {
  if (!left || !right || left === right) return;
  if (!graph.has(left)) graph.set(left, new Set());
  if (!graph.has(right)) graph.set(right, new Set());
  graph.get(left).add(right);
  graph.get(right).add(left);
}

function parseVariantCodes(value) {
  return value
    .split(/\s+/)
    .map((token) => token.replace(/<.*$/, ""))
    .filter((token) => /^U\+[0-9A-F]+$/i.test(token));
}

function readUnihanFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const text = fs.readFileSync(filePath, "utf8");
  for (const line of text.split(/\r?\n/)) {
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(U\+[0-9A-F]+)\s+(\S+)\s+(.+)$/);
    if (!match) continue;
    const [, code, field, value] = match;
    if (!safeVariantFields.has(field)) continue;
    const source = codepointToChar(code);
    for (const targetCode of parseVariantCodes(value)) {
      addPair(source, codepointToChar(targetCode));
    }
  }
}

readUnihanFile(variantsPath);
readUnihanFile(irgPath);
manualPairs.forEach(([left, right]) => addPair(left, right));

const result = {};
for (const [char, variants] of [...graph.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  result[char] = [...variants].sort((a, b) => a.localeCompare(b));
}

const body = [
  "// Generated by scripts/generate-han-variants.mjs.",
  "// Safe alias layer: compatibility, simplified/traditional, Z-variants, and curated Korean duplicate forms.",
  `const HAN_VARIANTS = ${JSON.stringify(result)};`,
  "",
].join("\n");

fs.writeFileSync(outputPath, body, "utf8");
console.log(`Done. chars=${Object.keys(result).length}, links=${Object.values(result).reduce((sum, list) => sum + list.length, 0) / 2}`);
