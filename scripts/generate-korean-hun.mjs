import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const officialCsvPath = path.join(root, "data/cache/hanja-grade-dataset-hanja.csv");
const fallbackPath = path.join(root, "data/cache/libhangul/hanja.txt");
const outputPath = path.join(root, "korean-hun.js");
const gradeOrder = [
  "8급",
  "7급Ⅱ",
  "7급",
  "6급Ⅱ",
  "6급",
  "5급Ⅱ",
  "5급",
  "4급Ⅱ",
  "4급",
  "3급Ⅱ",
  "3급",
  "2급",
  "1급",
  "특급Ⅱ",
  "특급",
];
const gradeRankByLevel = new Map(gradeOrder.map((level, index) => [level, index]));

function parseCsvLine(line) {
  const cells = [];
  let cell = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    if (char === "\"") {
      if (quoted && line[index + 1] === "\"") {
        cell += "\"";
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (char === "," && !quoted) {
      cells.push(cell);
      cell = "";
    } else {
      cell += char;
    }
  }
  cells.push(cell);
  return cells;
}

function addHun(map, char, reading, hun) {
  const cleanChar = String(char || "").trim().normalize("NFKC");
  const cleanReading = String(reading || "").trim();
  const cleanHun = normalizeHun(hun);
  if (!cleanChar || !cleanReading || !cleanHun) return;
  if (!map[cleanChar]) map[cleanChar] = {};
  if (!map[cleanChar][cleanReading]) map[cleanChar][cleanReading] = cleanHun;
}

function addGrade(map, char, level) {
  const cleanChar = String(char || "").trim().normalize("NFKC");
  const cleanLevel = String(level || "").trim();
  if (!cleanChar || !cleanLevel) return;
  const current = map[cleanChar];
  if (!current || gradeRank(cleanLevel) < gradeRank(current)) {
    map[cleanChar] = cleanLevel;
  }
}

function gradeRank(level) {
  return gradeRankByLevel.has(level) ? gradeRankByLevel.get(level) : Infinity;
}

function normalizeHun(hun) {
  return String(hun || "")
    .replace(/\p{Script=Han}/gu, " ")
    .replace(/[()[\]{}]/g, " ")
    .replace(/\s+/g, " ")
    .replace(/\s*[·ㆍ/]\s*/g, "ㆍ")
    .trim();
}

function parseOfficialMeaning(raw) {
  if (!raw) return [];
  try {
    const parsed = Function(`"use strict"; return (${raw});`)();
    return parsed.flatMap((item) => {
      const huns = Array.isArray(item?.[0]) ? item[0] : [];
      const readings = Array.isArray(item?.[1]) ? item[1] : [];
      const hun = huns.map(normalizeHun).filter(Boolean).join("ㆍ");
      return readings
        .map((reading) => String(reading || "").trim())
        .filter(Boolean)
        .map((reading) => ({ reading, hun }));
    });
  } catch {
    return [];
  }
}

function loadOfficial() {
  const map = {};
  const grades = {};
  const text = fs.readFileSync(officialCsvPath, "utf8").replace(/^\uFEFF/, "");
  const lines = text.split(/\r?\n/).filter(Boolean);
  const headers = parseCsvLine(lines.shift() || "");
  for (const line of lines) {
    const cells = parseCsvLine(line);
    const row = Object.fromEntries(headers.map((header, index) => [header, cells[index] || ""]));
    addGrade(grades, row.hanja, row.level);
    for (const item of parseOfficialMeaning(row.meaning)) {
      addHun(map, row.hanja, item.reading || row.main_sound, item.hun);
    }
  }
  return { map, grades };
}

function loadFallback() {
  const map = {};
  if (!fs.existsSync(fallbackPath)) return map;
  const text = fs.readFileSync(fallbackPath, "utf8").replace(/^\uFEFF/, "");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const [char, rest] = trimmed.split(/\s+/, 2);
    if (!char || !rest) continue;
    const match = rest.match(/^(.+?)([가-힣]+)$/);
    if (!match) continue;
    addHun(map, char, match[2], match[1]);
  }
  return map;
}

function mergeFallback(target, fallback) {
  for (const [char, readings] of Object.entries(fallback)) {
    for (const [reading, hun] of Object.entries(readings)) {
      addHun(target, char, reading, hun);
    }
  }
}

const { map: officialMap, grades: officialGrades } = loadOfficial();
const fallbackMap = loadFallback();
const officialCount = Object.keys(officialMap).length;
mergeFallback(officialMap, fallbackMap);

const sorted = Object.fromEntries(
  Object.entries(officialMap)
    .sort(([a], [b]) => a.localeCompare(b, "ko"))
    .map(([char, readings]) => [
      char,
      Object.fromEntries(Object.entries(readings).sort(([a], [b]) => a.localeCompare(b, "ko"))),
    ]),
);

const readingCount = Object.values(sorted).reduce((sum, readings) => sum + Object.keys(readings).length, 0);
const sortedGrades = Object.fromEntries(
  Object.entries(officialGrades).sort(([a], [b]) => {
    const rankDiff = gradeRank(officialGrades[a]) - gradeRank(officialGrades[b]);
    if (rankDiff !== 0) return rankDiff;
    return a.localeCompare(b, "ko");
  }),
);
const output = `// Generated by scripts/generate-korean-hun.mjs.\n`
  + `// Primary source: 한국어문회 배정한자 전체 대표훈음 CSV mirror.\n`
  + `// Official-source characters: ${officialCount}; merged characters: ${Object.keys(sorted).length}; readings: ${readingCount}.\n`
  + `const KOREAN_HANJA_GRADES = ${JSON.stringify(sortedGrades, null, 2)};\n`
  + `const KOREAN_HUN = ${JSON.stringify(sorted, null, 2)};\n`;

fs.writeFileSync(outputPath, output, "utf8");
console.log(`Wrote ${outputPath}`);
console.log(`official characters=${officialCount}, merged characters=${Object.keys(sorted).length}, readings=${readingCount}`);
